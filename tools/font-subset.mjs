// Builds the Google Fonts URL (kept in js/fonts-link.js) with `&text=`: every font is cut down to the characters the game can show.
// The CJK faces are the bulk of a cold load (about 1 MB as unicode-range slices); the game's text is all in its own
// strings, so the glyphs it can ever need are known. Run after adding strings with new characters:
//   node tools/font-subset.mjs           print the URL and the glyph count
//   node tools/font-subset.mjs --write   rewrite js/fonts-link.js
//   node tools/font-subset.mjs --check   exit 1 with a clear message when js/fonts-link.js is out of date (CI runs this)
// tests/unit-tech.mjs fails when the link is out of date with the strings.
// Merge conflict in js/fonts-link.js: take either side, then run --write. It is one generated line.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const FAMILIES = "family=IM+Fell+English+SC&family=Barlow+Semi+Condensed:wght@500;600;700&family=Noto+Serif+TC:wght@600&family=Noto+Sans+TC:wght@500";
// Printable ASCII always (numbers, gold, names), plus every non-ASCII character in the scripts, styles and the page.
export function glyphs() {
  const read = dir => readdirSync(new URL(dir, ROOT)).filter(f => /\.(js|css)$/.test(f)).map(f => readFileSync(new URL(dir + f, ROOT), "utf8"));
  const src = read("js/").concat(read("css/"),readFileSync(new URL("index.html", ROOT), "utf8"));
  const set = new Set();
  for (let c = 32; c < 127; c++) set.add(String.fromCharCode(c));
  for (const s of src) for (const ch of s) if (ch.codePointAt(0) > 127 && !/[\s\p{Cc}\p{Cf}\u{FE0F}]/u.test(ch)) set.add(ch);
  return [...set].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join("");
}
export function fontsHref() {
  return `https://fonts.googleapis.com/css2?${FAMILIES}&display=swap&text=${encodeURIComponent(glyphs())}`;
}
export const LINK_FILE = new URL("js/fonts-link.js", ROOT);
const HEADER = "// GENERATED by tools/font-subset.mjs --write; do not edit by hand. On a merge conflict here, take either side and re-run the tool.\n";
export function linkSource(href = fontsHref()) {
  // JSON.stringify: encodeURIComponent leaves ' ( ) * ! ~ alone, so a single-quoted literal would break on the apostrophe
  return HEADER + `document.write(${JSON.stringify(`<link id="fonts" rel="stylesheet" href="${href}">`)});\n`;
}
export function currentHref() {
  const m = readFileSync(LINK_FILE, "utf8").match(/href=\\"([^"\\]*)\\"/);
  return m ? m[1] : "";
}
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())) {
  const href = fontsHref(), n = [...glyphs()].length;
  if (process.argv.includes("--write")) {
    writeFileSync(LINK_FILE, linkSource(href));
    console.log(`js/fonts-link.js: ${n} glyphs`);
  } else if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = currentHref(); } catch {}
    if (cur === href) console.log(`fonts: js/fonts-link.js is up to date (${n} glyphs)`);
    else {
      const have = new Set([...(new URL(cur || "http://x/?text=").searchParams.get("text") || "")]);
      const missing = [...glyphs()].filter(c => !have.has(c)).join("");
      console.error(`::error file=js/fonts-link.js::The font subset is out of date${missing ? " (missing: " + missing + ")" : ""}. Run: node tools/font-subset.mjs --write  and commit js/fonts-link.js`);
      process.exit(1);
    }
  } else console.log(href, `\n${n} glyphs, URL ${href.length} chars`);
}
