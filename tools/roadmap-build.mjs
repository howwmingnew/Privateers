// Refresh the roadmap from GitHub issues labelled `enhancement`:
//   roadmap/issues.js           snapshot the roadmap page draws first (and from file://)
//   roadmap/roadmap-overview.svg  README art: every phase on one rail
//   roadmap/roadmap-current.svg   README art: the phase being worked on now
// Run by .github/workflows/roadmap.yml on every issue change; locally: `node tools/roadmap-build.mjs`.
// GITHUB_TOKEN is optional (raises the API rate limit); the repo is public.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "roadmap");

vm.runInThisContext(fs.readFileSync(path.join(OUT, "roadmap-core.js"), "utf8"), { filename: "roadmap-core.js" });
const RC = globalThis.RoadmapCore;

async function fetchIssues() {
  const headers = { Accept: "application/vnd.github+json", "User-Agent": "privateers-roadmap" };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const all = [];
  for (let page = 1; page <= 10; page++) {
    const url = `https://api.github.com/repos/${RC.REPO}/issues?labels=enhancement&state=all&per_page=100&page=${page}`;
    const r = await fetch(url, { headers });
    if (!r.ok) throw new Error(`GitHub API ${r.status} ${r.statusText} for ${url}`);
    const batch = await r.json();
    if (!Array.isArray(batch)) throw new Error("GitHub API returned something other than a list");
    all.push(...batch);
    if (batch.length < 100) break;
  }
  return all;
}

// Keep only what the page needs, so the committed snapshot stays small and holds no user data beyond the issue itself.
function slim(issue) {
  return {
    number: issue.number, title: issue.title, state: issue.state, html_url: issue.html_url, body: issue.body || "",
    labels: (issue.labels || []).map(l => ({ name: typeof l === "string" ? l : l.name })),
    ...(issue.pull_request ? { pull_request: true } : {}),
  };
}

// The model's fetch time is left out of the SVGs, so a run with no issue change leaves the files byte-identical.
function writeIfChanged(file, text) {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

const raw = await fetchIssues();
const issues = raw.filter(i => !i.pull_request).map(slim).sort((a, b) => a.number - b.number);
const model = RC.buildModel(issues, null);
if (!model.phases.length) throw new Error("no roadmap issues found (is the `<!-- roadmap: … -->` line missing?)");

const lang = process.env.ROADMAP_LANG === "en" ? "en" : "zh";
// GitHub draws README images at most ~830 px wide; a 1200 px canvas shrank the labels to ~7 px, so the README art
// is drawn narrower (phases wrap 4 per row, cards 3 per row) and lands close to 1:1.
const README_FIT = { width: 880 };
const prevSnap = path.join(OUT, "issues.js");
const prevIssues = fs.existsSync(prevSnap) ? fs.readFileSync(prevSnap, "utf8").match(/"issues":([\s\S]*)\};\s*$/) : null;
const issuesJson = JSON.stringify(issues);
// Only bump fetchedAt when the issues themselves changed, again so idle runs commit nothing.
const fetchedAt = prevIssues && prevIssues[1] === issuesJson
  ? JSON.parse(fs.readFileSync(prevSnap, "utf8").replace(/^[\s\S]*?=\s*/, "").replace(/;\s*$/, "")).fetchedAt
  : new Date().toISOString();

const changed = [
  writeIfChanged(prevSnap, `// Generated by tools/roadmap-build.mjs from GitHub issues labelled enhancement. Do not edit.\nwindow.ROADMAP_SNAPSHOT = {"fetchedAt":${JSON.stringify(fetchedAt)},"issues":${issuesJson}};\n`),
  writeIfChanged(path.join(OUT, "roadmap-overview.svg"), RC.renderOverview(model, lang, { slug: "roadmap-overview", ...README_FIT, perRow: 4 }) + "\n"),
  writeIfChanged(path.join(OUT, "roadmap-current.svg"), RC.renderPhase(model, model.current, lang, { slug: "roadmap-current", ...README_FIT, cols: 3 }) + "\n"),
].some(Boolean);

console.log(`${model.total} features in ${model.phases.length} phases, ${model.done} done, current phase ${model.current}; ${changed ? "files updated" : "no change"}`);
